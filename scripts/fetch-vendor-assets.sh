#!/usr/bin/env bash
#
# Downloads the front-end assets the site used to pull from third-party CDNs, so
# they can be served from our own domain instead.
#
# Why: every request to fonts.googleapis.com, fonts.gstatic.com or cdn.jsdelivr.net
# handed the visitor's IP address to that company before the page had even
# rendered — a transfer to a third party that is not necessary to provide the
# service, since the same files can be served from here. Self-hosting removes the
# recipient entirely rather than disclosing it.
#
# Run once before deploying, and again whenever a pinned version below changes:
#
#     bash scripts/fetch-vendor-assets.sh
#
# The downloaded files are build output, not source: public/vendor and public/fonts
# are git-ignored, so a fresh checkout (or a deploy) has to run this script. The
# templates reference these paths, so WITHOUT running it the pages lose Alpine and
# Dropzone and stop working. It is idempotent — safe to re-run.
#
# Requires: curl, unzip.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR="$ROOT/public/vendor"
FONTS="$ROOT/public/fonts"

ALPINE_VERSION="3.14.9"
DROPZONE_VERSION="6.0.0-beta.2"

# A desktop UA so Google Fonts returns woff2 (it serves older formats to unknown
# clients, and we only want to store one modern format).
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"

# Great Vibes is the handwritten line on the colour page (a caption and the
# stylist's signature); it is one of the few scripts with a Cyrillic subset.
# Prata carries the account dashboard's headlines. Playfair Display is the
# display serif elsewhere: a high-contrast Didone like the Bodoni Moda it
# replaced, but with Cyrillic, so Ukrainian headings no longer fall back to a
# system face. Montserrat is the body face: Jost, which it replaced, has a
# Cyrillic subset without the Ukrainian і ї є ґ, so they came from a system
# font. Manrope is the body face of the "Примірка" screen (the design hand-over).
# Every face here must cover both English and Ukrainian.
FONT_CSS_URL="https://fonts.googleapis.com/css2?family=Playfair+Display:ital,wght@0,400;0,500;0,600;0,700;1,400;1,500&family=Montserrat:wght@300;400;500&family=Prata&family=Great+Vibes&family=Manrope:wght@400;500;600;700&display=swap"

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }

mkdir -p "$VENDOR" "$FONTS"

say "1/3  Alpine.js $ALPINE_VERSION"
curl -fsSL "https://cdn.jsdelivr.net/npm/alpinejs@${ALPINE_VERSION}/dist/cdn.min.js" -o "$VENDOR/alpine.min.js"

say "2/3  Dropzone $DROPZONE_VERSION"
curl -fsSL "https://cdn.jsdelivr.net/npm/dropzone@${DROPZONE_VERSION}/dist/dropzone-min.js" -o "$VENDOR/dropzone.min.js"
curl -fsSL "https://cdn.jsdelivr.net/npm/dropzone@${DROPZONE_VERSION}/dist/dropzone.css" -o "$VENDOR/dropzone.css"

say "3/3  Fonts (Playfair Display, Montserrat, Prata, Great Vibes, Manrope)"
# Fetch the stylesheet Google would have served, then rewrite every remote font
# URL to a local one and store the files next to it.
CSS="$(curl -fsSL -H "User-Agent: $UA" "$FONT_CSS_URL")"

: > "$FONTS/fonts.css"
{
  printf '/* Self-hosted copies of Playfair Display, Montserrat, Prata, Great Vibes, Manrope.\n'
  printf '   Generated by scripts/fetch-vendor-assets.sh — do not edit by hand.\n'
  printf '   Served from our own domain so that rendering the page does not disclose\n'
  printf "   the visitor's IP address to a font host. */\n\n"
} >> "$FONTS/fonts.css"

count=0
while IFS= read -r line; do
  url="$(printf '%s' "$line" | grep -oE 'https://fonts\.gstatic\.com/[^)]+' || true)"
  if [ -n "$url" ]; then
    file="$(basename "${url%%\?*}")"
    if [ ! -f "$FONTS/$file" ]; then
      curl -fsSL "$url" -o "$FONTS/$file"
      count=$((count + 1))
    fi
    line="${line//$url/./$file}"
  fi
  printf '%s\n' "$line" >> "$FONTS/fonts.css"
done <<< "$CSS"
printf '     %s font file(s)\n' "$count"

say "Done."
printf 'Assets are in public/vendor and public/fonts.\n'
printf 'Verify no external host is referenced any more:\n'
printf '    grep -rn "googleapis\\|gstatic\\|jsdelivr" resources/views/\n'
printf '(Cloudflare Turnstile stays: it is a security control, not an asset host.)\n'
